const FMAlgorithmDef& FMAlgorithm::getAlgorithm(int algorithmIndex) noexcept {
    if (algorithmIndex < 0 || algorithmIndex >= FM_ALGORITHM_COUNT) {
        return algorithms_[0];
    }
    return algorithms_[algorithmIndex];
}

bool FMAlgorithm::isCarrier(int algorithmIndex, int operatorIndex) noexcept {
    const auto& algo = getAlgorithm(algorithmIndex);
    for (uint8_t i = 0; i < algo.carrierCount; ++i) {
        if (algo.carriers[i] == operatorIndex) {
            return true;
        }
    }
    return false;
}

